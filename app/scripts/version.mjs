// Writes the build id (git short hash + time) the app shows and polls for updates.
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";

const hash = (() => {
  try {
    return execSync("git rev-parse --short HEAD", { stdio: ["ignore", "pipe", "ignore"] })
      .toString()
      .trim();
  } catch {
    return "dev";
  }
})();
const build = `${hash}-${new Date().toISOString().slice(0, 16).replace(/[-:T]/g, "")}`;
mkdirSync("public", { recursive: true });
writeFileSync("public/version.json", JSON.stringify({ build }));
writeFileSync(
  "src/build.ts",
  `/** Generated by scripts/version.mjs before every build. */\nexport const BUILD: string = "${build}";\n`,
);
console.log(`build ${build}`);
