// Writes api/src/selfhost/migrations.generated.ts from api/migrations/*.sql, so the self-hosted
// server's database applies exactly the migrations Cloudflare's D1 gets, in the same order.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const dir = join(root, "api/migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const entries = files.map((name) => `  { name: ${JSON.stringify(name)}, sql: ${JSON.stringify(readFileSync(join(dir, name), "utf8"))} },`);
const out = `// Generated by scripts/selfhost-migrations.mjs from api/migrations; do not edit.
export const MIGRATIONS: { name: string; sql: string }[] = [
${entries.join("\n")}
];
`;
writeFileSync(join(root, "api/src/selfhost/migrations.generated.ts"), out);
console.log(`${files.length} migrations`);
